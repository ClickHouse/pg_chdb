/*
 * Settings pg_chdb protects because it controls them for Native transport,
 * session representation, or security. When pg_chdb starts controlling
 * another setting, add its canonical name or setting-family prefix here.
 */
static const protectedSetting protected_settings[] = {
    { "input_format_native_",                      true  },
    { "output_format_native_",                     true  },
    { "output_format_json_quote_denormals",        false },
    { "date_time_output_format",                   false },
    { "format_display_secrets_in_show_and_select", false },
};

static bool
starts_with(const char* value, const char* prefix) {
    return strncmp(value, prefix, strlen(prefix)) == 0;
}

/*
 * PostgreSQL folds unquoted option names to lowercase. Restrict generic
 * prefixed ClickHouse format-setting options to lowercase ASCII identifiers
 * because the canonical name is emitted as an identifier in the helper's
 * parameterized SET statement.
 */
static bool
valid_format_setting_name(const char* value) {
    for (const unsigned char* pos = (const unsigned char*)value; *pos; pos++) {
        if (!(*pos == '_' || (*pos >= 'a' && *pos <= 'z') ||
              (*pos >= '0' && *pos <= '9'))) {
            return false;
        }
    }

    return true;
}

bool
chdb_format_setting_protected(const char* name) {
    for (size_t i = 0; i < lengthof(protected_settings); i++) {
        const protectedSetting* setting = &protected_settings[i];

        if ((setting->prefix && starts_with(name, setting->name)) ||
            (!setting->prefix && strcmp(name, setting->name) == 0)) {
            return true;
        }
    }

    return false;
}

const char*
chdb_format_setting_name(const char* option) {
    for (size_t i = 0; i < lengthof(setting_aliases); i++) {
        if (strcmp(option, setting_aliases[i].alias) == 0) {
            return setting_aliases[i].canonical;
        }
    }

    for (size_t i = 0; i < lengthof(prefixed_settings); i++) {
        const char* canonical = prefixed_settings[i];

        if (strcmp(option, canonical + 7) == 0) {
            return canonical;
        }
    }

    /* These names are self-identifying, so chDB can validate new additions. */
    if (valid_format_setting_name(option) &&
        (starts_with(option, "format_") || starts_with(option, "input_format_") ||
         starts_with(option, "output_format_"))) {
        return option;
    }

    for (size_t i = 0; i < lengthof(unprefixed_settings); i++) {
        if (strcmp(option, unprefixed_settings[i]) == 0) {
            return unprefixed_settings[i];
        }
    }

    return NULL;
}
